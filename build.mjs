// Bundles the ES modules in js/ into one classic script (js/sallo.bundle.js) so the app also
// opens from a plain file:// double-click, where browsers refuse <script type="module">.
// No dependencies. Run: node build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname, relative } from 'node:path';

const root = resolve('js');
const entry = resolve(root, 'app.js');
const mods = new Map(); // abs path -> { id, code, deps }
const order = [];

function load(file, stack = []) {
  if (mods.has(file)) { if (!mods.get(file).done) throw new Error('Circular import: ' + [...stack, file].map((f) => relative(root, f)).join(' -> ')); return; }
  const m = { id: relative(root, file), done: false };
  mods.set(file, m);
  let src = readFileSync(file, 'utf8');
  const exportsList = [];
  const reqId = (spec) => relative(root, resolve(dirname(file), spec));
  const dep = (spec) => { const f = resolve(dirname(file), spec); load(f, [...stack, file]); return reqId(spec); };

  // import ... from '...'
  src = src.replace(/^import\s+([^;'"]*?)\s+from\s+'([^']+)';?[ \t]*$/gm, (_, what, spec) => {
    const id = dep(spec);
    what = what.trim();
    if (what.startsWith('* as ')) return `const ${what.slice(5).trim()} = __req(${JSON.stringify(id)});`;
    const inner = what.replace(/^\{|\}$/g, '').split(',').map((s) => s.trim()).filter(Boolean)
      .map((s) => s.replace(/\s+as\s+/, ': ')).join(', ');
    return `const { ${inner} } = __req(${JSON.stringify(id)});`;
  });
  src = src.replace(/^import\s+'([^']+)';?[ \t]*$/gm, (_, spec) => `__req(${JSON.stringify(dep(spec))});`);

  src = src.replace(/^export\s+(async\s+function|function|class|const|let)\s+([A-Za-z0-9_$]+)/gm, (_, kind, name) => { exportsList.push(name); return `${kind} ${name}`; });
  src = src.replace(/^export\s*\{([^}]*)\};?[ \t]*$/gm, (_, names) => { names.split(',').map((s) => s.trim()).filter(Boolean).forEach((n) => exportsList.push(n)); return ''; });
  if (/^\s*(import|export)\s/m.test(src.replace(/`[\s\S]*?`/g, ''))) {
    const bad = src.split('\n').find((l) => /^(import|export)\s/.test(l));
    if (bad) throw new Error(`Unhandled module syntax in ${m.id}: ${bad}`);
  }
  m.code = `__def(${JSON.stringify(m.id)}, function (__exports) {\n${src}\n${exportsList.map((n) => `__exports.${n} = ${n};`).join('\n')}\n});`;
  m.done = true;
  order.push(m);
}
load(entry);

const out = `/* Sallo — generated by build.mjs from js/*.js. Do not edit; edit the modules and rebuild. */
(function () {
'use strict';
var __defs = {}, __cache = {};
function __def(id, fn) { __defs[id] = fn; }
function __req(id) {
  if (__cache[id]) return __cache[id];
  var ex = __cache[id] = {};
  __defs[id](ex);
  return ex;
}
${order.map((m) => m.code).join('\n')}
__req(${JSON.stringify(relative(root, entry))});
})();
`;
writeFileSync(resolve(root, 'sallo.bundle.js'), out);
console.log(`bundled ${order.length} modules, ${(out.length / 1024).toFixed(0)} KB`);
